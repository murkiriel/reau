package com.reau.app.video

import kotlin.math.abs
import kotlin.math.exp
import kotlin.math.tanh

/**
 * Which Android Auto screen is open (the map, the app launcher, or another app), from the tiny 64x40 copy of the picture that the compositor takes,
 * WITHOUT the Accessibility service. A hand-written, dependency-free little neural net (stdlib only): 8x5 blocks, 132 inputs, 1 hidden layer of 24 tanh units, 3 outputs, 3267 weights.
 * Cost per call: about 3240 multiply-adds (the 64x40 pass over the pixels is the bulk), about 40 us on a desktop JVM, an estimated 0.15 to 0.3 ms on a 32-bit phone (not measured there); no allocation in [classify] with a given [Result].
 *
 * What it does, step by step (every number below is a constant of the trained model, see the tables at the end of the file):
 *  1. Black gate: if 92% or more of the pixels are black (luma < 16) the picture is the black screen of an opening/transition: UNSURE.
 *  2. Features (132 numbers): the picture is reduced to 8x5 blocks of 8x8 pixels (mean of each block), and each block gives 3 numbers (luma, blue-minus-luma, red-minus-luma, each scaled to about -1..1);
 *     then adds 4 texture numbers (mean luma step to the next pixel along x and y, share of steps above 12) and the 8-bin luma histogram.
 *  3. One hidden layer of 24 units (tanh) and 3 outputs (NAV, MENU, APPS). The z-score normalisation of the training set and the temperature
 *     of the calibration (T = 1.05) are already folded into the weights, so the 3 outputs are calibrated logits; the confidence is the softmax of the winner.
 *  4. Abstention: if the confidence is below [MIN_CONFIDENCE] (0.9) the answer is UNSURE.
 *
 * Trained on 24/10/2026 on 6150 labelled frames (owner's phone, Android Auto 17.x, and the test phone, Android Auto 11.8; the protocols and numbers of the study are in [PictureLook]);
 * retrained on 25/10 and on 27/10/2026 on 7426 frames (see [PictureLook]). It is a picture classifier: like [PictureLook], it can be wrong on screens it has never seen (a full-screen album cover in a day theme,
 * a notification card laid over the map...), so the caller should keep using the displays/focus when they say something and use this only where they say nothing.
 * Not thread-safe (work buffers are reused): call it from one thread (the compositor's).
 */
object ScreenNet {
    enum class Screen { NAV, MENU, APPS, UNSURE }

    /** The answer. Reuse one instance with the 4-argument [classify] to avoid any allocation. */
    class Result(@JvmField var screen: Screen = Screen.UNSURE, @JvmField var confidence: Float = 0f)

    /** The size of the tiny copy the compositor takes of the picture (the same as [PictureLook]). */
    const val SAMPLE_W = 64
    const val SAMPLE_H = 40

    /** Below this confidence (calibrated softmax of the winner) the answer is UNSURE. Chosen on the inner validation only. */
    const val MIN_CONFIDENCE = 0.9f

    /** At least this share (percent) of black pixels (luma < 16): opening logo, black screen, fade. UNSURE without asking the net. */
    const val BLACK_GATE_PERCENT = 92

    private const val W = SAMPLE_W
    private const val H = SAMPLE_H
    private const val PIXELS = SAMPLE_W * SAMPLE_H
    private const val BLOCK = 8
    private const val GRID_W = 8
    private const val GRID_H = 5
    private const val FEATURES = 132
    private const val HIDDEN = 24

    private val luma = IntArray(PIXELS)          // luma x 1000 (299 R + 587 G + 114 B), exact
    private val feat = FloatArray(FEATURES)
    private val hid = FloatArray(HIDDEN)
    private val outBuf = FloatArray(4)             // calibrated logits (3) and the confidence

    /** The class of [rgba] ([width] x [height] must be 64 x 40, 4 bytes a pixel) and how sure the net is (0 to 1). Allocates one small [Result]. */
    fun classify(rgba: ByteArray, width: Int, height: Int): Result = classify(rgba, width, height, Result())

    /** The same, written into [into] (no allocation). A picture of another size or a short array is UNSURE with confidence 0. */
    @Synchronized
    fun classify(rgba: ByteArray, width: Int, height: Int, into: Result): Result {
        if (width != W || height != H || rgba.size < PIXELS * 4) {
            into.screen = Screen.UNSURE; into.confidence = 0f
            return into
        }
        val black = infer(rgba, outBuf)
        val k = decide(black, outBuf)
        into.screen = when (k) { 0 -> Screen.NAV; 1 -> Screen.MENU; 2 -> Screen.APPS; else -> Screen.UNSURE }
        into.confidence = outBuf[3]
        return into
    }

    /** The three calibrated logits of the last call (for tests): NAV, MENU, APPS. */
    fun lastLogits(): FloatArray = floatArrayOf(outBuf[0], outBuf[1], outBuf[2])

    // ---- BEGIN-TRANSCRIBE (the part below is written in a plain subset of Kotlin on purpose, so that it can be transcribed mechanically to Python for the equivalence proof) ----

    /**
     * Fills [o] with the 3 calibrated logits; returns the number of black pixels. One long function on purpose: the pixel pass, the features and the two layers are
     * written in a plain subset of Kotlin (loops, Int and Float, no helpers) so that the study could transcribe this text mechanically to Python and prove it does the
     * same as an independent C implementation on all 7612 frames; cutting it up would void that proof.
     */
    @Suppress("LongMethod", "CyclomaticComplexMethod", "NestedBlockDepth")
    private fun infer(rgba: ByteArray, o: FloatArray): Int {
        var black = 0
        for (p in 0 until PIXELS) {
            val q = p * 4
            val r = (rgba[q].toInt() and 0xFF)
            val g = (rgba[q + 1].toInt() and 0xFF)
            val b = (rgba[q + 2].toInt() and 0xFF)
            val y = 299 * r + 587 * g + 114 * b
            luma[p] = y
            if (y < 16000) black = black + 1
        }
        var k = 0
        for (by in 0 until GRID_H) {
            for (bx in 0 until GRID_W) {
                var sr = 0
                var sg = 0
                var sb = 0
                for (yy in 0 until BLOCK) {
                    for (xx in 0 until BLOCK) {
                        val q = ((by * BLOCK + yy) * W + bx * BLOCK + xx) * 4
                        sr = sr + (rgba[q].toInt() and 0xFF)
                        sg = sg + (rgba[q + 1].toInt() and 0xFF)
                        sb = sb + (rgba[q + 2].toInt() and 0xFF)
                    }
                }
                val inv = 1.0f / (BLOCK * BLOCK).toFloat()
                val fr = sr.toFloat() * inv
                val fg = sg.toFloat() * inv
                val fb = sb.toFloat() * inv
                val yv = 0.299f * fr + 0.587f * fg + 0.114f * fb
                feat[k] = (yv - 128.0f) / 128.0f
                feat[k + 1] = (fb - yv) / 128.0f
                feat[k + 2] = (fr - yv) / 128.0f
                k = k + 3
            }
        }
        // texture: how much the luma changes from a pixel to the next one (a map is full of lines, a card or a menu is flat)
        var exi = 0
        var eyi = 0
        var cx = 0
        var cy = 0
        for (yy in 0 until H) {
            for (xx in 0 until W) {
                val v = luma[yy * W + xx]
                if (xx + 1 < W) {
                    val d = abs(luma[yy * W + xx + 1] - v)
                    exi = exi + d
                    if (d > 12000) cx = cx + 1
                }
                if (yy + 1 < H) {
                    val d = abs(luma[(yy + 1) * W + xx] - v)
                    eyi = eyi + d
                    if (d > 12000) cy = cy + 1
                }
            }
        }
        feat[k] = (exi.toDouble() / 1000.0 / ((W - 1) * H).toDouble() / 255.0 * 8.0).toFloat()
        feat[k + 1] = (eyi.toDouble() / 1000.0 / ((H - 1) * W).toDouble() / 255.0 * 8.0).toFloat()
        feat[k + 2] = cx.toFloat() / ((W - 1) * H).toFloat()
        feat[k + 3] = cy.toFloat() / ((H - 1) * W).toFloat()
        k = k + 4
        // luma histogram: 8 bins (edges 0, 12, 24, 36, 48, 64, 96, 160, 256), share of the pixels in each
        for (t in 0 until 8) feat[k + t] = 0.0f
        for (p in 0 until PIXELS) {
            val y = luma[p]
            var bin = 0
            for (e in 1 until 8) {
                if (y >= HIST_EDGE[e]) bin = e
            }
            feat[k + bin] = feat[k + bin] + 1.0f
        }
        for (t in 0 until 8) feat[k + t] = feat[k + t] / PIXELS.toFloat()
        k = k + 8
        for (j in 0 until HIDDEN) {
            var s = B1[j]
            val base = j * FEATURES
            for (i in 0 until FEATURES) {
                s = s + W1[base + i] * feat[i]
            }
            hid[j] = tanh(s.toDouble()).toFloat()
        }
        for (c in 0 until 3) {
            var s = B2[c]
            val base = c * HIDDEN
            for (j in 0 until HIDDEN) {
                s = s + W2[base + j] * hid[j]
            }
            o[c] = s
        }
        return black
    }

    /** 0 NAV, 1 MENU, 2 APPS, 3 UNSURE; puts the confidence (softmax of the winner, 0 when gated) in o[3]. */
    private fun decide(black: Int, o: FloatArray): Int {
        if (black * 100 >= BLACK_GATE_PERCENT * PIXELS) {
            o[3] = 0f
            return 3
        }
        var best = 0
        if (o[1] > o[best]) best = 1
        if (o[2] > o[best]) best = 2
        val top = o[best]
        val total = exp((o[0] - top).toDouble()) + exp((o[1] - top).toDouble()) + exp((o[2] - top).toDouble())
        o[3] = (1.0 / total).toFloat()
        if (o[3] < MIN_CONFIDENCE) return 3
        return best
    }

